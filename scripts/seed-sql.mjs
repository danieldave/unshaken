// Run: node scripts/seed-sql.mjs  → writes supabase/seed_listings.sql from supabase/seed/*.json
// Every seeded row is status 'draft': nothing goes public until the owner approves it in /admin.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { normUrl } from "../api/_queue.js";

const dir = new URL("../supabase/seed/", import.meta.url);
const q = v => v === null || v === undefined || v === "" ? "null" : `'${String(v).replace(/'/g, "''")}'`;
const j = v => `'${JSON.stringify(v ?? null).replace(/'/g, "''")}'::jsonb`;
const arr = a => `array[${(a || []).map(q).join(",")}]::text[]`;
let out = "-- Generated by scripts/seed-sql.mjs. Paste into Supabase → SQL Editor AFTER 002_listings.sql.\n-- All rows are DRAFTS. Re-running is safe: existing links are skipped.\n";
for (const f of readdirSync(dir).filter(f => f.endsWith(".json")).sort()) {
  const d = JSON.parse(readFileSync(new URL(f, dir)));
  out += `\n-- ${f}: ${d.items.length} listings, verified ${d.verified_on}\n`;
  for (const it of d.items) {
    out += `insert into listings (id,status,cat,title,get,who,steps,link,link_norm,source_url,due,due_text,rolling,opens,elig,tags,flag,notes,origin,verified_on) values (${[
      q(it.id), "'draft'", q(it.cat), q(it.title), q(it.get), q(it.who), j(it.steps), q(it.link), q(normUrl(it.link)), q(it.source_url),
      it.due ? `${q(it.due)}::timestamptz` : "null", q(it.due_text), it.rolling ? "true" : "false", it.opens ? "true" : "false", j(it.elig || {}), arr(it.tags), q(it.flag), q(it.notes), "'seed'", q(d.verified_on)
    ].join(",")}) on conflict do nothing;\n`;
  }
}
writeFileSync(new URL("../supabase/seed_listings.sql", import.meta.url), out);
console.log("Wrote supabase/seed_listings.sql");
